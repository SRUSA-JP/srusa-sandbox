/**
 * 拡大縮小と移動の操作設定。
 *
 * ワールドマップと相関図で同じ操作感にするため、刻み幅や下限・上限は
 * この 1 ファイルだけが持つ。計算そのものは lib/viewport.ts。
 *
 * 拡大率は「全体を収めた大きさの何倍か」で持つ。内容の大きさが場面ごとに
 * 違うので、px の絶対値で持つと同じ設定が別の意味になってしまう。
 */

/** 場面ごとの拡大できる範囲。 */
export interface ZoomRange {
  /** 全体を収めた大きさの何倍まで縮められるか。 */
  min: number;
  /** 何倍まで拡大できるか。 */
  max: number;
}

export const VIEWPORT = {
  /** ボタン・キーで 1 回に変える倍率。 */
  step: 1.5,
  /**
   * ホイール 1 目盛りあたりの倍率の底。
   * `step ** (移動量 / この値)` で連続的に変える。
   */
  wheelDivisor: 260,
  /** 矢印キーで動かす距離（画面上の px）。 */
  keyPan: 48,
  /**
   * これ以上動いたら「掴んで動かした」と見なす距離（px）。
   * 指で触れると必ず数 px 動くので、押しっぱなしと区別するために要る。
   */
  dragThreshold: 4,
} as const;

/** ワールドマップ（1 内容画素 = 1 ブロック）。 */
export const WORLD_MAP_ZOOM: ZoomRange = {
  /** 全体より小さくしても意味が無いので、収まる大きさが下限。 */
  min: 1,
  /** 1 ブロックがはっきり四角に見えるところまで。 */
  max: 24,
};

/** 相関図（1 内容単位 = SVG の 1 単位）。 */
export const RELATIONSHIP_ZOOM: ZoomRange = {
  /**
   * 全体を収めた大きさから、さらに数回ぶん引けるようにする。
   *
   * 0.8 だと 1 回引いただけで下限に着き、それ以上ボタンが効かない
   * （1 回の倍率が 1.5 なので、1 回で 0.67 倍まで下がるため）。
   * 縮小できないように見えるので、3 回ぶん引ける値にする。
   */
  min: 0.3,
  /** 名前とアイコンを大きく確かめられるところまで。 */
  max: 6,
};
